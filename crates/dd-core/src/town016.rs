impl Deployment {
    pub fn battle_input(
        &self,
        monsters: Vec<Blueprint>,
        mut rules: Rules,
        seed: u64,
        mut supplies: Vec<dd_data::items::SupplyStack>,
        catalog: BTreeMap<String, Blueprint>,
    ) -> Result<crate::api012::BattleInput> {
        rules.host_return_token = Some(self.token.clone());
        if rules.context.as_ref().map(|c| c.region.as_str()) != self.quest.raw["dungeon"].as_str() {
            return Err("battle region differs from departing quest".into());
        }
        if rules
            .context
            .as_ref()
            .is_some_and(|c| !c.trinket_inventory.is_empty())
        {
            return Err("carried trinkets require expedition physical asset mapping".into());
        }
        if rules.content.id()? != self.quest.content_id {
            return Err("deployment battle content differs".into());
        }
        if let Some(table) = &self.bonuses.lighting {
            rules
                .lighting
                .as_mut()
                .ok_or("district requires battle lighting context")?
                .table = table.clone();
        }
        for stack in &mut supplies {
            if let Some(replacement) = self.bonuses.replacements.get(&stack.definition.id) {
                stack.definition = replacement.clone();
            }
        }
        Ok(crate::api012::BattleInput {
            scenario: crate::Scenario {
                heroes: self.heroes.clone(),
                monsters,
                rules,
                round_limit: 1000,
            },
            seed,
            supplies,
            catalog,
            waves: vec![],
        })
    }
}
impl HostQuest {
    fn validate(&self, content: &str) -> Result<()> {
        if self.content_id != content
            || self.id.is_empty()
            || self.id.len() > 200
            || self.source.trim().is_empty()
            || self.source.len() > 2000
            || self.raw["dungeon"].as_str().is_none()
            || uint(&self.raw, "difficulty")? > 6
            || self.raw["completion_reward"].as_object().is_none()
        {
            return Err("invalid source-valued host mission contract".into());
        }
        uint(&self.raw["completion_reward"], "resolve_xp")?;
        uint(&self.raw, "length")?;
        Ok(())
    }
}
/// Every field is an explicit bonus obligation. A host must acknowledge all domains
/// before departure; a combat-only consumer cannot silently discard expedition rules.
#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Bonuses {
    pub field_buffs: BTreeMap<u64, Vec<dd_data::mechanics::Buff>>,
    pub curio: Vec<Value>,
    pub camping: Vec<Value>,
    pub disable_hunger: bool,
    pub stacking: Vec<Value>,
    pub supplies: Vec<Stack>,
    pub replacements: BTreeMap<String, dd_data::items::Supply>,
    pub loot_darkness: Option<Value>,
    pub lighting: Option<dd_data::lighting::Darkness>,
    pub prestige: bool,
}
impl Bonuses {
    pub fn domains(&self) -> BTreeSet<String> {
        let mut d = BTreeSet::new();
        if !self.field_buffs.is_empty() {
            d.insert("field_buffs".into());
        }
        if !self.curio.is_empty() {
            d.insert("curio".into());
        }
        if !self.camping.is_empty() {
            d.insert("camping".into());
        }
        if self.disable_hunger {
            d.insert("hunger".into());
        }
        if !self.stacking.is_empty() {
            d.insert("stacking".into());
        }
        if !self.supplies.is_empty() {
            d.insert("provision".into());
        }
        if self.loot_darkness.is_some() {
            d.insert("loot".into());
        }
        d
    }
}
