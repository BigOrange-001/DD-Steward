#[derive(Clone)]
pub struct Definition {
    game: Arc<GameData>,
    data: Arc<Data>,
    id: String,
    opening: crate::opening015::Definition,
    cache: Arc<Mutex<BTreeMap<Vec<u8>, Blueprint>>>,
    trinkets: Arc<Mutex<BTreeMap<String, dd_data::trinket010::Trinket>>>,
}
impl Definition {
    pub fn load(game: GameData, candidates: Candidates) -> Result<Self> {
        let data = Data::load(&game, candidates)?;
        Self::new(game, data)
    }
    fn new(game: GameData, data: Data) -> Result<Self> {
        use sha2::{Digest, Sha256};
        let game = Arc::new(game);
        let opening = crate::opening015::Definition::from_shared(game.clone(), data.base.clone())?;
        let raw = serde_json::to_vec(&(&data, opening.id())).map_err(|e| e.to_string())?;
        let id = format!("{PROFILE};sha256:{:x}", Sha256::digest(raw));
        Ok(Self {
            game,
            data: Arc::new(data),
            id,
            opening,
            cache: Arc::new(Mutex::new(BTreeMap::new())),
            trinkets: Arc::new(Mutex::new(BTreeMap::new())),
        })
    }
    fn trinket(&self, id: &str) -> Result<dd_data::trinket010::Trinket> {
        if let Some(d) = self
            .trinkets
            .lock()
            .map_err(|_| "town cache poisoned")?
            .get(id)
            .cloned()
        {
            return Ok(d);
        }
        let catalog = self.game.trinket_catalog(&[id.into()])?;
        let result = catalog.get(id).ok_or("missing trinket root")?.clone();
        self.trinkets
            .lock()
            .map_err(|_| "town cache poisoned")?
            .extend(catalog);
        Ok(result)
    }
    pub fn id(&self) -> &str {
        &self.id
    }
    pub fn data(&self) -> &Data {
        &self.data
    }
}
